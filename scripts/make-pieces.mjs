// Generates the piece art: src/assets/pieces.svg, one <symbol id="piece-X"> per piece type, drawn in
// scripts/pieces/ (original drawings for this project, MIT like the rest of it). The colours are CSS
// variables (--piece-fill, --piece-line, --piece-detail), so the game can draw any piece in any
// colours from one drawing (src/ui/boardDom.ts, src/style.css).
//
// Run: node scripts/make-pieces.mjs  (then commit the generated sprite)
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { render } from './pieces/draw.mjs';
import { FAIRY } from './pieces/fairy.mjs';
import { FUSIONS } from './pieces/fusions.mjs';
import { STANDARD } from './pieces/standard.mjs';

export const DRAWINGS = { ...STANDARD, ...FAIRY, ...FUSIONS };

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const out = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'assets', 'pieces.svg');
  const symbols = Object.entries(DRAWINGS).map(
    ([type, drawing]) => `<symbol id="piece-${type}" viewBox="0 0 100 100">${render(drawing)}</symbol>`,
  );
  writeFileSync(
    out,
    `<!-- Generated by scripts/make-pieces.mjs: edit the drawings there, not this file. -->\n<svg xmlns="http://www.w3.org/2000/svg">\n${symbols.join('\n')}\n</svg>\n`,
  );
  console.log(`Wrote ${Object.keys(DRAWINGS).length} pieces to src/assets/pieces.svg`);
}
